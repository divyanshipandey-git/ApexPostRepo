using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Storage.ValueConversion;

namespace ApexPost.IntegrationTests.TestSupport;

/// <summary>
/// The production model is written for SQL Server (nvarchar(max), datetime2, SYSUTCDATETIME() defaults, rowversion).
/// SQLite cannot create those. This customizer runs after OnModelCreating and removes only the SQL Server specific
/// parts, keeping tables, keys, relationships, indexes, lengths and nullability, so repository queries still run
/// through the real EF Core pipeline. What SQLite therefore does NOT prove is listed in TESTING-STRATEGY.md section 6.
/// </summary>
internal sealed class SqliteModelCustomizer(ModelCustomizerDependencies dependencies) : ModelCustomizer(dependencies)
{
    public override void Customize(ModelBuilder modelBuilder, DbContext context)
    {
        base.Customize(modelBuilder, context);

        foreach (var entityType in modelBuilder.Model.GetEntityTypes())
        {
            // CHECK constraints use T-SQL functions such as LEN(); they are SQL Server behaviour, not repository logic.
            foreach (var check in entityType.GetCheckConstraints().ToList())
            {
                entityType.RemoveCheckConstraint(check.ModelName);
            }

            foreach (var property in entityType.GetProperties())
            {
                property.SetColumnType(null);
                // Keep "has a database default" semantics (EF seed data relies on it) but with SQLite syntax.
                if (property.GetDefaultValueSql() is not null)
                {
                    property.SetDefaultValueSql("CURRENT_TIMESTAMP");
                }

                property.SetComputedColumnSql(null);

                // SQLite cannot ORDER BY / compare DateTimeOffset as text reliably; store as sortable ticks.
                if (property.ClrType == typeof(DateTimeOffset) || property.ClrType == typeof(DateTimeOffset?))
                {
                    property.SetValueConverter(new DateTimeOffsetToBinaryConverter());
                }

                // rowversion is generated by SQL Server only.
                if (property.ValueGenerated == ValueGenerated.OnAddOrUpdate && property.IsConcurrencyToken)
                {
                    property.ValueGenerated = ValueGenerated.Never;
                    property.IsConcurrencyToken = false;
                    property.IsNullable = true;
                }
            }
        }
    }
}
